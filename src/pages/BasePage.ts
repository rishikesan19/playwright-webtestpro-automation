import type { Page, Response } from '@playwright/test';
import { HeaderNav } from '@components/HeaderNav';

/** Shared behaviour for every page: navigation by relative path and the site-wide header. */
export abstract class BasePage {
  readonly header: HeaderNav;
  protected abstract readonly path: string;

  constructor(protected readonly page: Page) {
    this.header = new HeaderNav(page);
  }

  /** Navigates relative to the configured baseURL and returns the main document response. */
  async open(): Promise<Response | null> {
    return this.navigate(this.path);
  }

  /**
   * Navigates without waiting for the `load` event. Product images are generated by the origin
   * (`/get_product_picture/<id>`) and can take 30s+ each under load, which delays `load` far beyond
   * the point where the page is usable. Tests synchronise on web-first assertions instead.
   */
  protected async navigate(path: string): Promise<Response | null> {
    return this.page.goto(path, { waitUntil: 'domcontentloaded' });
  }

  /**
   * The site binds its jQuery handlers (add to cart, remove, contact submit, reviews) directly in
   * synchronous scripts at the end of <body>, some behind a slow Google Maps script. Elements are
   * visible and clickable before those handlers exist, and an early click silently falls back to
   * default browser behaviour. DOMContentLoaded fires only after every synchronous script has run,
   * so it is a deterministic readiness check that, unlike `load`, does not wait for slow images.
   */
  protected async waitForPageScripts(): Promise<void> {
    await this.page.waitForLoadState('domcontentloaded');
  }
}
